import { readFile } from "node:fs/promises";
import { PDFDocument, rgb, type PDFFont, type PDFPage } from "pdf-lib";
import fontkit from "@pdf-lib/fontkit";
import type { AuditEvent } from "./audit";

const ink = rgb(0.09, 0.14, 0.18);
const muted = rgb(0.38, 0.44, 0.48);
const accent = rgb(0.17, 0.56, 0.47);
const line = rgb(0.87, 0.9, 0.91);
const paper = rgb(0.97, 0.98, 0.97);

function wrap(text: string, font: PDFFont, size: number, width: number) {
  const lines: string[] = [];
  for (const paragraph of text.split(/\n/)) {
    let current = "";
    for (const word of paragraph.split(/\s+/).filter(Boolean)) {
      const candidate = current ? `${current} ${word}` : word;
      if (font.widthOfTextAtSize(candidate, size) > width && current) {
        lines.push(current);
        current = word;
      } else {
        current = candidate;
      }
    }
    lines.push(current);
  }
  return lines;
}

function drawWrapped(page: PDFPage, text: string, x: number, y: number, width: number, font: PDFFont, size: number, color = ink, lineHeight = size * 1.4) {
  const lines = wrap(text, font, size, width);
  lines.forEach((entry, index) => page.drawText(entry, { x, y: y - index * lineHeight, size, font, color }));
  return y - lines.length * lineHeight;
}

function sectionHeader(page: PDFPage, title: string, x: number, y: number, font: PDFFont) {
  page.drawText(title, { x, y, size: 10, font, color: accent });
  page.drawLine({ start: { x, y: y - 7 }, end: { x: 540, y: y - 7 }, thickness: 0.6, color: line });
}

export async function createEvidencePdf(input: {
  organization: string;
  email: string;
  from?: string;
  to?: string;
  events: AuditEvent[];
  chainValid: boolean;
}) {
  const document = await PDFDocument.create();
  document.registerFontkit(fontkit);
  const regularBytes = await readFile(new URL("../assets/fonts/DejaVuSans.ttf", import.meta.url));
  const boldBytes = await readFile(new URL("../assets/fonts/DejaVuSans-Bold.ttf", import.meta.url));
  const regular = await document.embedFont(regularBytes);
  const bold = await document.embedFont(boldBytes);
  document.setTitle("Article50Kit evidence pack");
  document.setAuthor("Article50Kit");
  document.setSubject("Customer-submitted AI transparency implementation records");
  document.setCreator("Article50Kit evidence export");

  const pages: PDFPage[] = [];
  const pageCount = Math.max(1, Math.ceil(input.events.length / 5) + 1);
  for (let index = 0; index < pageCount; index++) {
    const page = document.addPage([612, 792]);
    pages.push(page);
    page.drawRectangle({ x: 0, y: 0, width: 612, height: 792, color: paper });
    page.drawRectangle({ x: 0, y: 770, width: 612, height: 22, color: ink });
    page.drawText("ARTICLE50KIT  /  TRANSPARENCY EVIDENCE", { x: 38, y: 778, size: 8, font: bold, color: rgb(1, 1, 1) });
    page.drawLine({ start: { x: 38, y: 34 }, end: { x: 574, y: 34 }, thickness: 0.6, color: line });
    page.drawText(`Generated ${new Date().toISOString()}  |  Page ${index + 1} of ${pageCount}`, { x: 38, y: 20, size: 7, font: regular, color: muted });
  }

  const first = pages[0];
  first.drawText("Evidence pack", { x: 38, y: 714, size: 30, font: bold, color: ink });
  first.drawText("AI transparency implementation records", { x: 38, y: 690, size: 12, font: regular, color: muted });
  first.drawText(input.organization.slice(0, 100), { x: 38, y: 654, size: 15, font: bold, color: ink });
  first.drawText(input.email, { x: 38, y: 636, size: 9, font: regular, color: muted });
  first.drawText(`Exported: ${new Date().toISOString()}`, { x: 38, y: 615, size: 9, font: regular, color: muted });
  first.drawText(`Range: ${input.from ?? "all recorded history"}  to  ${input.to ?? "now"}`, { x: 38, y: 599, size: 8, font: regular, color: muted });

  sectionHeader(first, "RECORD SUMMARY", 38, 558, bold);
  const summary = [
    ["Disclosure and handling records", String(input.events.length)],
    ["Hash-chain integrity in exported database", input.chainValid ? "Verified" : "FAILED - review required"],
    ["Signed C2PA media records", String(input.events.filter((event) => event.event_type === "c2pa_media_mark").length)],
  ];
  summary.forEach(([label, value], index) => {
    const y = 532 - index * 27;
    first.drawText(label, { x: 38, y, size: 9, font: regular, color: muted });
    first.drawText(value, { x: 376, y, size: 9, font: bold, color: label.startsWith("Hash") && !input.chainValid ? rgb(0.7, 0.1, 0.1) : ink });
  });

  sectionHeader(first, "IMPORTANT LIMITATIONS", 38, 431, bold);
  drawWrapped(first,
    "This export contains records submitted by your integration and an integrity check of the stored event sequence. Article50Kit cannot independently prove that a notice was rendered, read, or understood by an end user; that an uploaded asset was generated by AI; or that a C2PA credential is trusted by a recipient's verifier. A valid signature and legal compliance are different questions. This report is technical evidence, not legal advice or a certificate of compliance.",
    38, 409, 536, regular, 9, ink, 14,
  );
  first.drawText("No conversation text or user message body is stored in these event records.", { x: 38, y: 322, size: 8, font: bold, color: accent });

  sectionHeader(first, "EVENT REGISTER", 38, 283, bold);
  first.drawText(input.events.length ? "Detailed records follow on the next page." : "No events are present in this selected date range.", { x: 38, y: 261, size: 9, font: regular, color: muted });

  input.events.forEach((event, index) => {
    const pageIndex = 1 + Math.floor(index / 5);
    const eventPage = pages[pageIndex];
    const slot = index % 5;
    const top = 718 - slot * 140;
    const kind = event.event_type.replaceAll("_", " ").toUpperCase();
    eventPage.drawText(kind, { x: 38, y: top, size: 9, font: bold, color: accent });
    eventPage.drawText(event.received_at, { x: 355, y: top, size: 8, font: regular, color: muted });
    eventPage.drawText(`${event.surface}  |  ${event.locale}  |  policy ${event.policy_version}`, { x: 38, y: top - 17, size: 8, font: regular, color: muted });
    drawWrapped(eventPage, `Notice: ${event.notice || "(empty)"}`, 38, top - 36, 536, regular, 8, ink, 11);
    eventPage.drawText(`Reported at: ${event.client_reported_at ?? "not supplied"}`, { x: 38, y: top - 80, size: 7, font: regular, color: muted });
    eventPage.drawText(`Content SHA-256: ${event.content_sha256 ?? "not supplied"}`, { x: 38, y: top - 93, size: 7, font: regular, color: muted });
    eventPage.drawText(`Event SHA-256: ${event.event_hash}`, { x: 38, y: top - 106, size: 7, font: regular, color: muted });
    eventPage.drawLine({ start: { x: 38, y: top - 119 }, end: { x: 574, y: top - 119 }, thickness: 0.5, color: line });
  });

  return document.save();
}
